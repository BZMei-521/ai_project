export interface WorkflowDependency {
  kind: WorkflowDependencyKind;
  name: string;
  required?: boolean;
}

export interface WorkflowOutputSpec {
  nodeId?: string;
  nodeType?: string;
  filenamePrefix?: string;
  extension?: string;
}

export interface StoryboardWorkflowDefinition {
  id: string;
  stage: StoryboardWorkflowStage;
  quality: StoryboardWorkflowQuality;
  workflowJson: string;
  requiredTokens: WorkflowTokenSpec[];
  optionalTokens?: WorkflowTokenSpec[];
  dependencies: WorkflowDependency[];
  output: WorkflowOutputSpec;
}

export type WorkflowCapabilityErrorCode = "missing_token" | "missing_dependency" | "unavailable_node" | "invalid_definition";

export interface WorkflowCapabilityError {
  code: WorkflowCapabilityErrorCode;
  message: string;
  token?: string;
  dependency?: WorkflowDependency;
}

export interface WorkflowEnvironment {
  tokens?: string | Iterable<string> | Record<string, unknown>;
  dependencies?: string | Iterable<string> | Record<string, unknown>;
  availableDependencies?: string | Iterable<string> | Record<string, unknown>;
  nodes?: string | Iterable<string> | Record<string, unknown>;
  availableNodes?: string | Iterable<string> | Record<string, unknown>;
}

export interface WorkflowCapabilityReport {
  definition: StoryboardWorkflowDefinition;
  available: boolean;
  errors: WorkflowCapabilityError[];
  missingTokens: string[];
  missingDependencies: WorkflowDependency[];
}

export interface StoryboardWorkflowSelection {
  selected: WorkflowCapabilityReport | null;
  rejected: WorkflowCapabilityReport[];
}

