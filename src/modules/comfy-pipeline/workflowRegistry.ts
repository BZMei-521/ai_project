export type StoryboardWorkflowStage = "stageA" | "stageB" | "fallback";
export type StoryboardWorkflowQuality = "mature_asset_guided" | "builtin_zimage" | "builtin_qwen" | "single_pass";
export type WorkflowDependencyKind = "checkpoint" | "vae" | "diffusion_model" | "text_encoder" | "controlnet" | "ipadapter" | "custom_node" | "node";

export interface WorkflowTokenSpec {
  token: string;
  required?: boolean;
  description?: string;
}

