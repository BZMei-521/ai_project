import assert from "node:assert/strict";
import { build } from "esbuild";
const result = await build({ entryPoints: ["src/modules/spatial-stage/mogeWorkflow.ts", "src/modules/spatial-stage/mogeRunner.ts", "src/modules/spatial-stage/comfyMogeTransport.ts"], absWorkingDir: process.cwd(), bundle: true, format: "esm", platform: "node", target: "node20", outdir: ".moge-check", write: false });
const modules = await Promise.all(result.outputFiles.map((file) => import(`data:text/javascript;base64,${Buffer.from(file.text).toString("base64")}`)));
const workflowRuntime = modules.find((item) => item.buildMogePanoramaWorkflow);
const runnerRuntime = modules.find((item) => item.runMogeInitialization);
const transportRuntime = modules.find((item) => item.createComfyMogeTransport);
const workflow = workflowRuntime.buildMogePanoramaWorkflow({ image: "C:\\assets\\panorama.png" });
assert.equal(workflow["1"].inputs.image, "panorama.png");
assert.equal(workflow["2"].inputs.model_name, "moge_2_vitl_normal_fp16.safetensors");
assert.equal(workflow["3"].inputs.split_resolution, 512);
assert.equal(workflow["3"].inputs.merge_resolution, 1920);
assert.deepEqual(workflow["4"].inputs.moge_geometry, ["3", 0]);
for (const id of ["5", "6", "7"]) assert.deepEqual(workflow[id].inputs.moge_geometry, ["3", 0]);
assert.equal(workflowRuntime.auditMogeWorkflow(workflow).valid, true);
const broken = structuredClone(workflow); broken["4"].inputs.moge_geometry = ["1", 0];
assert.equal(workflowRuntime.auditMogeWorkflow(broken).valid, false);
let queued = false;
const fallback = await runnerRuntime.runMogeInitialization({ image: "panorama.png" }, { overall: "manual_fallback", mogeNode: { status: "manual_fallback" }, mogeModel: { status: "manual_fallback" } }, { queue: async () => { queued = true; return "unexpected"; } });
assert.equal(fallback.status, "manual_fallback"); assert.equal(queued, false);
const live = await runnerRuntime.runMogeInitialization({ image: "panorama.png" }, { overall: "available", mogeNode: { status: "available" }, mogeModel: { status: "available" } }, { queue: async () => "prompt-1" });
assert.equal(live.status, "queued"); assert.equal(live.promptId, "prompt-1");
const completed = await runnerRuntime.runMogeInitialization({ image: "panorama.png" }, { overall: "available", mogeNode: { status: "available" }, mogeModel: { status: "available" } }, { queue: async () => "prompt-2", wait: async () => ({ outputs: { depthUrl: "depth.png", normalUrl: "normal.png", maskUrl: "mask.png" } }) });
assert.equal(completed.status, "completed"); assert.equal(completed.outputs.depthUrl, "depth.png");
const requests = [];
const transport = transportRuntime.createComfyMogeTransport({ baseUrl: "http://127.0.0.1:8188/", fetchImpl: async (url, init) => {
  requests.push([url, init?.method]);
  return { ok: true, status: 200, json: async () => requests.length === 1 ? { prompt_id: "p-1" } : { "p-1": { outputs: {} } } };
} });
assert.equal(await transport.queue(workflow), "p-1");
assert.deepEqual(requests[0], ["http://127.0.0.1:8188/prompt", "POST"]);
await transport.wait("p-1");
assert.match(requests[1][0], /\/history\/p-1$/);
console.log("spatial stage MoGe checks passed");
